"""Derive packages.txt from a traced runtime session.

Usage: packages.py <node_modules> <trace.txt> > packages.txt

A package is used when the session imported or read one of its files other than package.json
(dsh reads every manifest while it builds its resolution scope). The list keeps those packages
and their declared dependencies, so lazily loaded code paths inside a used package still resolve.
A few packages declare far more than this profile uses; they are kept without their dependency
fan-out, and the trace decides which of their dependencies stay.
"""
import json
import os
import sys

# dsh is the CLI meta-package (every bundle), dsh-sdk-app is the full `sdk` profile (Office,
# desktop UI), pi-ai bundles every model provider's SDK, and node-addon-require-builtin lists
# every platform's binary. dsh-base links dsh to the plugins Agent S's patch inserts, so dsh can
# resolve them; it is kept for that link alone.
SHALLOW = {
    '@deepseek-ai/dsh',
    '@deepseek-ai/dsh-base',
    '@deepseek-ai/dsh-sdk-app',
    '@earendil-works/pi-ai',
    'node-addon-require-builtin',
}
ALWAYS = ['@deepseek-ai/dsh-base']


def package_of(root, path):
    path = os.path.realpath(path)
    if not path.startswith(root + '/'):
        return None
    parts = path[len(root) + 1:].split('/')
    names, i = [], 0
    while i < len(parts):
        width = 2 if parts[i].startswith('@') else 1
        if i + width > len(parts):
            break
        names.append('/'.join(parts[i:i + width]))
        i += width
        if i < len(parts) and parts[i] == 'node_modules':
            i += 1
        else:
            break
    return '/node_modules/'.join(names) or None


def resolve(root, origin, dependency):
    current = origin
    while True:
        candidate = current + '/node_modules/' + dependency if current else dependency
        if os.path.isfile(os.path.join(root, candidate, 'package.json')):
            return candidate
        if not current:
            return None
        current = current.rsplit('/node_modules/', 1)[0] if '/node_modules/' in current else ''


def main():
    root = os.path.realpath(sys.argv[1])
    used = set()
    for line in open(sys.argv[2]):
        path = line.strip()
        if path.endswith('/package.json') or not os.path.isfile(path):
            continue
        package = package_of(root, path)
        if package and os.path.isfile(os.path.join(root, package, 'package.json')):
            used.add(package)
    keep, stack, missing = set(), sorted(used) + ALWAYS, []
    while stack:
        package = stack.pop()
        if package in keep:
            continue
        keep.add(package)
        if package in SHALLOW:
            continue
        manifest = json.load(open(os.path.join(root, package, 'package.json')))
        for field in ('dependencies', 'optionalDependencies', 'peerDependencies'):
            for dependency in manifest.get(field, {}):
                found = resolve(root, package, dependency)
                if found:
                    stack.append(found)
                elif field == 'dependencies':
                    missing.append(f'{package} -> {dependency}')
    print(f'{len(used)} used, {len(keep)} kept', file=sys.stderr)
    if missing:
        sys.exit('Missing required dependencies:\n' + '\n'.join(missing))
    print('# Generated by scripts/vendor-deepseek.sh --trace. Do not edit by hand.')
    for package in sorted(keep):
        print(package)


if __name__ == '__main__':
    main()
